// Package attachment stores files a user uploads for one Agent Run (for
// example images or documents chosen in the trial console or a service order
// form). Contents and metadata live only in a dedicated local directory owned
// by the Core process; the Run input carries a short-lived capability link.
// Attachments are bound to the Run that uses them and released once that Run
// is terminal, or when they expire unused. Core never opens, converts or
// executes attachment contents.
package attachment

import (
	"context"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"strings"
	"sync"
	"sync/atomic"
	"time"
	"unicode"

	"github.com/google/uuid"
)

const (
	MaxFileBytes          = 30 * 1000 * 1000
	MaxPerRun             = 20
	DefaultOwnerMaxCount  = 40
	DefaultOwnerMaxBytes  = int64(1000 * 1000 * 1000)
	DefaultInstanceBytes  = int64(10 * 1000 * 1000 * 1000)
	DefaultUnboundTTL     = 24 * time.Hour
	DefaultBoundLifetime  = 7 * 24 * time.Hour
	DefaultMinFreeBytes   = int64(2 * 1000 * 1000 * 1000)
	DefaultMinFreePercent = 10
	staleTempAge          = time.Hour
	maxFilenameRunes      = 200
	KindImage             = "image"
	KindFile              = "file"
)

var (
	ErrNotFound     = errors.New("attachment not found, expired or released")
	ErrTooLarge     = errors.New("attachment is larger than the per-file limit")
	ErrEmpty        = errors.New("attachment is empty")
	ErrOwnerQuota   = errors.New("too many live attachments for this account")
	ErrInstanceFull = errors.New("attachment storage is full")
	ErrDiskLow      = errors.New("attachment disk free space is below the safety threshold")
)

// Config bounds one Store. Zero values take the defaults.
type Config struct {
	Dir              string
	OwnerMaxCount    int
	OwnerMaxBytes    int64
	InstanceMaxBytes int64
	UnboundTTL       time.Duration
	BoundLifetime    time.Duration
	MinFreeBytes     int64
	MinFreePercent   int
}

// Meta is the on-disk metadata of one attachment. Contents are never stored
// here and the capability token is stored only as its SHA-256.
type Meta struct {
	ID        string    `json:"id"`
	TokenHash string    `json:"token_hash"`
	Owner     string    `json:"owner"`
	Kind      string    `json:"kind"`
	MediaType string    `json:"media_type"`
	Filename  string    `json:"filename"`
	Size      int64     `json:"size"`
	SHA256    string    `json:"sha256"`
	CreatedAt time.Time `json:"created_at"`
	ExpiresAt time.Time `json:"expires_at"`
	RunID     string    `json:"run_id,omitempty"`
}

// Upload is the result of storing one attachment. Token is shown once.
type Upload struct {
	Meta
	Token string `json:"-"`
}

// Store is a local-directory attachment store. All paths are generated by
// the Store and every file operation goes through os.Root.
type Store struct {
	cfg   Config
	root  *os.Root
	dir   string
	mu    sync.Mutex
	total atomic.Int64
	now   func() time.Time
	// freeSpace reports (free, total) bytes of the filesystem holding dir.
	freeSpace func(string) (uint64, uint64, error)
}

var layout = []string{"blobs", "meta", "tokens", "owners", "runs", "tmp"}

// Open validates the directory (absolute, dedicated, real directory owned by
// this process with no group/other permissions), creates it if missing and
// prepares the layout. It never loosens or repairs another owner's directory.
func Open(cfg Config) (*Store, error) {
	dir := strings.TrimSpace(cfg.Dir)
	if dir == "" || !filepath.IsAbs(dir) {
		return nil, errors.New("attachment directory must be an absolute path")
	}
	dir = filepath.Clean(dir)
	if forbiddenDirectory(dir) {
		return nil, errors.New("attachment directory must not be the filesystem root or inside the system temporary directory")
	}
	if err := os.Mkdir(dir, 0o700); err != nil && !errors.Is(err, fs.ErrExist) {
		return nil, fmt.Errorf("create attachment directory: %w", err)
	}
	if err := checkPrivateDirectory(dir); err != nil {
		return nil, err
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return nil, fmt.Errorf("open attachment directory: %w", err)
	}
	for _, name := range layout {
		if err := root.Mkdir(name, 0o700); err != nil && !errors.Is(err, fs.ErrExist) {
			root.Close()
			return nil, fmt.Errorf("prepare attachment directory: %w", err)
		}
		if info, err := root.Lstat(name); err != nil || !info.IsDir() || info.Mode()&fs.ModeSymlink != 0 || info.Mode().Perm()&0o077 != 0 {
			root.Close()
			return nil, fmt.Errorf("attachment directory entry %q must be a private directory", name)
		}
	}
	if cfg.OwnerMaxCount <= 0 {
		cfg.OwnerMaxCount = DefaultOwnerMaxCount
	}
	if cfg.OwnerMaxBytes <= 0 {
		cfg.OwnerMaxBytes = DefaultOwnerMaxBytes
	}
	if cfg.InstanceMaxBytes <= 0 {
		cfg.InstanceMaxBytes = DefaultInstanceBytes
	}
	if cfg.UnboundTTL <= 0 {
		cfg.UnboundTTL = DefaultUnboundTTL
	}
	if cfg.BoundLifetime <= 0 {
		cfg.BoundLifetime = DefaultBoundLifetime
	}
	if cfg.MinFreeBytes < 0 {
		cfg.MinFreeBytes = 0
	} else if cfg.MinFreeBytes == 0 {
		cfg.MinFreeBytes = DefaultMinFreeBytes
	}
	if cfg.MinFreePercent <= 0 {
		cfg.MinFreePercent = DefaultMinFreePercent
	}
	cfg.Dir = dir
	s := &Store{cfg: cfg, root: root, dir: dir, now: time.Now, freeSpace: filesystemSpace}
	s.recountTotal()
	return s, nil
}

func (s *Store) Close() error { return s.root.Close() }

// Dir returns the validated absolute directory.
func (s *Store) Dir() string { return s.dir }

func forbiddenDirectory(dir string) bool {
	if dir == string(filepath.Separator) || filepath.Dir(dir) == dir {
		return true
	}
	for _, temp := range []string{os.TempDir(), "/tmp", "/var/tmp", "/private/tmp"} {
		temp = filepath.Clean(temp)
		if resolved, err := filepath.EvalSymlinks(temp); err == nil {
			for _, candidate := range []string{temp, resolved} {
				if dir == candidate || strings.HasPrefix(dir, candidate+string(filepath.Separator)) {
					return true
				}
			}
		}
	}
	return false
}

func checkPrivateDirectory(dir string) error {
	info, err := os.Lstat(dir)
	if err != nil {
		return fmt.Errorf("inspect attachment directory: %w", err)
	}
	if info.Mode()&fs.ModeSymlink != 0 || !info.IsDir() {
		return errors.New("attachment directory must be a real directory, not a symbolic link")
	}
	if info.Mode().Perm()&0o077 != 0 {
		return errors.New("attachment directory must not grant group or other permissions (use 0700)")
	}
	return checkOwner(info)
}

func randomID() string {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		panic(err)
	}
	return hex.EncodeToString(b)
}

func newToken() (string, string) {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		panic(err)
	}
	token := hex.EncodeToString(b)
	return token, hashToken(token)
}

func hashToken(token string) string {
	sum := sha256.Sum256([]byte(token))
	return hex.EncodeToString(sum[:])
}

func ownerDir(owner uuid.UUID) string {
	sum := sha256.Sum256([]byte(owner.String()))
	return path.Join("owners", hex.EncodeToString(sum[:]))
}

func blobPath(id string) string   { return path.Join("blobs", id[:2], id) }
func metaPath(id string) string   { return path.Join("meta", id[:2], id+".json") }
func tokenPath(h string) string   { return path.Join("tokens", h[:2], h) }
func runDir(run uuid.UUID) string { return path.Join("runs", run.String()) }

func validID(id string) bool {
	if len(id) != 32 {
		return false
	}
	_, err := hex.DecodeString(id)
	return err == nil
}

// ValidToken reports whether a value has the capability token shape.
func ValidToken(token string) bool {
	if len(token) != 64 {
		return false
	}
	_, err := hex.DecodeString(token)
	return err == nil && strings.ToLower(token) == token
}

// SanitizeFilename keeps a display name only: no directories, control
// characters or leading dots, bounded length. It is never used as a path.
func SanitizeFilename(name string) string {
	name = strings.ReplaceAll(name, "\\", "/")
	name = path.Base(strings.TrimSpace(name))
	var b strings.Builder
	count := 0
	for _, r := range name {
		if count >= maxFilenameRunes {
			break
		}
		if unicode.IsControl(r) || r == '/' || r == 0 {
			continue
		}
		b.WriteRune(r)
		count++
	}
	cleaned := strings.TrimLeft(strings.TrimSpace(b.String()), ".")
	if cleaned == "" || cleaned == "." {
		return "attachment"
	}
	return cleaned
}

// Put streams r into the store for owner. The body is bounded while reading,
// hashed, written to a private temporary file, synced and renamed into place
// before its metadata becomes visible. Any failure removes what was written.
func (s *Store) Put(ctx context.Context, owner uuid.UUID, filename string, r io.Reader) (*Upload, error) {
	if err := s.admit(owner); err != nil {
		return nil, err
	}
	id := randomID()
	tmp := path.Join("tmp", id)
	file, err := s.root.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return nil, fmt.Errorf("create attachment: %w", err)
	}
	cleanup := func() { _ = s.root.Remove(tmp) }
	hash := sha256.New()
	head := make([]byte, 0, 512)
	written, err := io.Copy(io.MultiWriter(file, hash, &prefixWriter{buf: &head}), io.LimitReader(r, MaxFileBytes+1))
	if err == nil {
		err = file.Sync()
	}
	closeErr := file.Close()
	if err == nil {
		err = closeErr
	}
	if err != nil {
		cleanup()
		return nil, fmt.Errorf("store attachment: %w", err)
	}
	if written > MaxFileBytes {
		cleanup()
		return nil, ErrTooLarge
	}
	if written == 0 {
		cleanup()
		return nil, ErrEmpty
	}
	if err := ctx.Err(); err != nil {
		cleanup()
		return nil, err
	}
	kind, mediaType := KindFile, "application/octet-stream"
	if image := SniffImage(head); image != "" {
		kind, mediaType = KindImage, image
	}
	token, tokenHash := newToken()
	now := s.now().UTC()
	meta := Meta{
		ID: id, TokenHash: tokenHash, Owner: owner.String(), Kind: kind, MediaType: mediaType,
		Filename: SanitizeFilename(filename), Size: written, SHA256: hex.EncodeToString(hash.Sum(nil)),
		CreatedAt: now, ExpiresAt: now.Add(s.cfg.UnboundTTL),
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.admitLocked(owner, written); err != nil {
		cleanup()
		return nil, err
	}
	if err := s.root.MkdirAll(path.Dir(blobPath(id)), 0o700); err != nil {
		cleanup()
		return nil, err
	}
	if err := s.root.Rename(tmp, blobPath(id)); err != nil {
		cleanup()
		return nil, err
	}
	if err := s.writeMeta(meta); err != nil {
		_ = s.root.Remove(blobPath(id))
		return nil, err
	}
	if err := s.writeMarker(tokenPath(tokenHash), id); err != nil {
		s.removeAll(meta)
		return nil, err
	}
	if err := s.writeMarker(path.Join(ownerDir(owner), id), ""); err != nil {
		s.removeAll(meta)
		return nil, err
	}
	s.total.Add(written)
	return &Upload{Meta: meta, Token: token}, nil
}

type prefixWriter struct{ buf *[]byte }

func (w *prefixWriter) Write(p []byte) (int, error) {
	if room := cap(*w.buf) - len(*w.buf); room > 0 {
		if room > len(p) {
			room = len(p)
		}
		*w.buf = append(*w.buf, p[:room]...)
	}
	return len(p), nil
}

// admit is a cheap pre-check so an over-quota upload is refused before its
// body is read; admitLocked repeats it with the real size before committing.
func (s *Store) admit(owner uuid.UUID) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.admitLocked(owner, 0)
}

func (s *Store) admitLocked(owner uuid.UUID, size int64) error {
	if free, total, err := s.freeSpace(s.dir); err == nil && total > 0 {
		threshold := uint64(s.cfg.MinFreeBytes)
		if percent := total * uint64(s.cfg.MinFreePercent) / 100; percent > threshold {
			threshold = percent
		}
		if free < threshold+uint64(size) {
			return ErrDiskLow
		}
	}
	if s.total.Load()+size > s.cfg.InstanceMaxBytes {
		return ErrInstanceFull
	}
	count, bytes := s.ownerUsage(owner)
	if count >= s.cfg.OwnerMaxCount || bytes+size > s.cfg.OwnerMaxBytes {
		return ErrOwnerQuota
	}
	return nil
}

func (s *Store) ownerUsage(owner uuid.UUID) (int, int64) {
	entries, err := fs.ReadDir(s.root.FS(), ownerDir(owner))
	if err != nil {
		return 0, 0
	}
	count, bytes := 0, int64(0)
	for _, entry := range entries {
		meta, err := s.readMeta(entry.Name())
		if err != nil {
			_ = s.root.Remove(path.Join(ownerDir(owner), entry.Name()))
			continue
		}
		count++
		bytes += meta.Size
	}
	return count, bytes
}

func (s *Store) writeMeta(meta Meta) error {
	raw, err := json.Marshal(meta)
	if err != nil {
		return err
	}
	if err := s.root.MkdirAll(path.Dir(metaPath(meta.ID)), 0o700); err != nil {
		return err
	}
	tmp := path.Join("tmp", meta.ID+".meta")
	if err := s.writeFile(tmp, raw); err != nil {
		return err
	}
	if err := s.root.Rename(tmp, metaPath(meta.ID)); err != nil {
		_ = s.root.Remove(tmp)
		return err
	}
	return nil
}

func (s *Store) writeMarker(name, content string) error {
	if err := s.root.MkdirAll(path.Dir(name), 0o700); err != nil {
		return err
	}
	return s.writeFile(name, []byte(content))
}

func (s *Store) writeFile(name string, data []byte) error {
	file, err := s.root.OpenFile(name, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0o600)
	if err != nil {
		return err
	}
	_, err = file.Write(data)
	if err == nil {
		err = file.Sync()
	}
	return errors.Join(err, file.Close())
}

func (s *Store) readMeta(id string) (Meta, error) {
	if !validID(id) {
		return Meta{}, ErrNotFound
	}
	raw, err := fs.ReadFile(s.root.FS(), metaPath(id))
	if err != nil {
		return Meta{}, ErrNotFound
	}
	var meta Meta
	if json.Unmarshal(raw, &meta) != nil || meta.ID != id {
		return Meta{}, ErrNotFound
	}
	return meta, nil
}

// Lookup resolves a live (not expired) attachment by its capability token.
func (s *Store) Lookup(token string) (Meta, error) {
	if !ValidToken(token) {
		return Meta{}, ErrNotFound
	}
	tokenHash := hashToken(token)
	raw, err := fs.ReadFile(s.root.FS(), tokenPath(tokenHash))
	if err != nil {
		return Meta{}, ErrNotFound
	}
	meta, err := s.readMeta(strings.TrimSpace(string(raw)))
	if err != nil || meta.TokenHash != tokenHash || !s.now().Before(meta.ExpiresAt) {
		return Meta{}, ErrNotFound
	}
	return meta, nil
}

// Open returns the contents of a live attachment for streaming.
func (s *Store) Open(token string) (Meta, *os.File, error) {
	meta, err := s.Lookup(token)
	if err != nil {
		return Meta{}, nil, err
	}
	file, err := s.root.Open(blobPath(meta.ID))
	if err != nil {
		return Meta{}, nil, ErrNotFound
	}
	if info, err := file.Stat(); err != nil || info.Size() != meta.Size || !info.Mode().IsRegular() {
		file.Close()
		return Meta{}, nil, ErrNotFound
	}
	return meta, file, nil
}

// Bind records that run uses the given attachments, extending their lifetime
// to the bound limit; the sweeper releases them once the Run is terminal.
func (s *Store) Bind(run uuid.UUID, ids []string) error {
	if len(ids) == 0 {
		return nil
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	var errs []error
	for _, id := range ids {
		meta, err := s.readMeta(id)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		meta.RunID = run.String()
		if until := s.now().UTC().Add(s.cfg.BoundLifetime); until.After(meta.ExpiresAt) {
			meta.ExpiresAt = until
		}
		if err := s.writeMarker(path.Join(runDir(run), id), ""); err != nil {
			errs = append(errs, err)
			continue
		}
		errs = append(errs, s.writeMeta(meta))
	}
	return errors.Join(errs...)
}

// ReleaseRun deletes every attachment bound to run.
func (s *Store) ReleaseRun(run uuid.UUID) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	entries, err := fs.ReadDir(s.root.FS(), runDir(run))
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil
		}
		return err
	}
	for _, entry := range entries {
		if meta, err := s.readMeta(entry.Name()); err == nil {
			s.removeAll(meta)
		}
	}
	return s.root.RemoveAll(runDir(run))
}

// removeAll deletes contents first, then indexes and metadata. Callers hold mu.
func (s *Store) removeAll(meta Meta) {
	if info, err := s.root.Stat(blobPath(meta.ID)); err == nil {
		s.total.Add(-info.Size())
	}
	_ = s.root.Remove(blobPath(meta.ID))
	if meta.TokenHash != "" && len(meta.TokenHash) == 64 {
		_ = s.root.Remove(tokenPath(meta.TokenHash))
	}
	if owner, err := uuid.Parse(meta.Owner); err == nil {
		_ = s.root.Remove(path.Join(ownerDir(owner), meta.ID))
	}
	_ = s.root.Remove(metaPath(meta.ID))
}

func (s *Store) recountTotal() {
	var total int64
	_ = fs.WalkDir(s.root.FS(), "blobs", func(name string, entry fs.DirEntry, err error) error {
		if err == nil && entry.Type().IsRegular() {
			if info, err := entry.Info(); err == nil {
				total += info.Size()
			}
		}
		return nil
	})
	s.total.Store(total)
}

// RunStatus reports a Run's status; found=false means the Run does not exist.
type RunStatus func(ctx context.Context, run uuid.UUID) (status string, found bool, err error)

// SweepResult summarizes one cleanup pass.
type SweepResult struct {
	ReleasedRuns, Expired, Orphans int
}

// Sweep releases attachments of terminal or missing Runs, expired attachments,
// and orphaned or stale temporary files. Errors are per item; the pass keeps
// going so one bad entry never blocks cleanup of the rest.
func (s *Store) Sweep(ctx context.Context, status RunStatus, terminal func(string) bool) (SweepResult, error) {
	var result SweepResult
	var errs []error
	runs, _ := fs.ReadDir(s.root.FS(), "runs")
	for _, entry := range runs {
		if ctx.Err() != nil {
			return result, ctx.Err()
		}
		run, err := uuid.Parse(entry.Name())
		if err != nil {
			_ = s.root.RemoveAll(path.Join("runs", entry.Name()))
			continue
		}
		current, found, err := status(ctx, run)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		if found && !terminal(current) {
			continue
		}
		if err := s.ReleaseRun(run); err != nil {
			errs = append(errs, err)
			continue
		}
		result.ReleasedRuns++
	}
	now := s.now()
	s.mu.Lock()
	_ = fs.WalkDir(s.root.FS(), "meta", func(name string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() || !strings.HasSuffix(entry.Name(), ".json") {
			return nil
		}
		meta, readErr := s.readMeta(strings.TrimSuffix(entry.Name(), ".json"))
		if readErr != nil {
			if info, err := entry.Info(); err == nil && now.Sub(info.ModTime()) > staleTempAge {
				_ = s.root.Remove(name)
				result.Orphans++
			}
			return nil
		}
		if !now.Before(meta.ExpiresAt) {
			s.removeAll(meta)
			if run, err := uuid.Parse(meta.RunID); err == nil {
				_ = s.root.Remove(path.Join(runDir(run), meta.ID))
			}
			result.Expired++
		}
		return nil
	})
	// Contents without metadata (for example a crash mid-upload) and stale
	// temporary files are removed once older than an hour.
	for _, area := range []string{"blobs", "tmp", "tokens"} {
		_ = fs.WalkDir(s.root.FS(), area, func(name string, entry fs.DirEntry, err error) error {
			if err != nil || entry.IsDir() {
				return nil
			}
			info, err := entry.Info()
			if err != nil || now.Sub(info.ModTime()) <= staleTempAge {
				return nil
			}
			orphan := area == "tmp"
			switch area {
			case "blobs":
				_, metaErr := s.readMeta(entry.Name())
				orphan = metaErr != nil
			case "tokens":
				raw, readErr := fs.ReadFile(s.root.FS(), name)
				if readErr != nil {
					orphan = true
				} else if meta, metaErr := s.readMeta(strings.TrimSpace(string(raw))); metaErr != nil || meta.TokenHash != entry.Name() {
					orphan = true
				}
			}
			if orphan {
				_ = s.root.Remove(name)
				result.Orphans++
			}
			return nil
		})
	}
	s.mu.Unlock()
	s.recountTotal()
	return result, errors.Join(errs...)
}

// Run sweeps every interval until ctx ends.
func (s *Store) Run(ctx context.Context, interval time.Duration, status RunStatus, terminal func(string) bool, report func(SweepResult, error)) {
	if interval <= 0 {
		interval = 5 * time.Minute
	}
	tick := func() {
		result, err := s.Sweep(ctx, status, terminal)
		if report != nil {
			report(result, err)
		}
	}
	tick()
	ticker := time.NewTicker(interval)
	defer ticker.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
			tick()
		}
	}
}

// SniffImage identifies JPEG, PNG, WebP or GIF by signature only.
func SniffImage(data []byte) string {
	switch {
	case len(data) >= 3 && data[0] == 0xFF && data[1] == 0xD8 && data[2] == 0xFF:
		return "image/jpeg"
	case len(data) >= 8 && string(data[:8]) == "\x89PNG\r\n\x1a\n":
		return "image/png"
	case len(data) >= 6 && (string(data[:6]) == "GIF87a" || string(data[:6]) == "GIF89a"):
		return "image/gif"
	case len(data) >= 12 && string(data[:4]) == "RIFF" && string(data[8:12]) == "WEBP":
		return "image/webp"
	}
	return ""
}
